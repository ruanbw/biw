-- Initial schema. docker-compose mounts this file into PostgreSQL's
-- /docker-entrypoint-initdb.d, so it runs once on the first start of an empty
-- volume. A schema change is made in this file; existing development data is
-- rebuilt with `docker compose down -v`, or altered by hand in a real database.
--
-- The database (biw) and the role (biw) are created by the official PostgreSQL
-- image through POSTGRES_DB / POSTGRES_USER.

-- ---------------------------------------------------------------------------
-- Enum types
-- ---------------------------------------------------------------------------
-- State columns are native enum types, not VARCHAR plus a CHECK: the value set
-- is then a real type, so `\dT` lists it, a typo is rejected before it reaches
-- a row, and the values cannot drift between tables. The Java enums
-- (UserStatus, RoleStatus) carry the same names, and PostgresEnumTypeHandler
-- binds them by name.
--
-- CREATE TYPE has no IF NOT EXISTS, so a DO block keeps the file re-runnable.
-- Adding a value later is `ALTER TYPE ... ADD VALUE`; removing or renaming one
-- means recreating the type and rewriting the column, which is the price of
-- having the value set in the database instead of in a CHECK.
DO $$
BEGIN
    CREATE TYPE user_status AS ENUM ('ENABLED', 'DISABLED');
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
    CREATE TYPE role_status AS ENUM ('ENABLED', 'DISABLED');
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

-- ---------------------------------------------------------------------------
-- sys_user
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sys_user (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    nickname      VARCHAR(64)  NOT NULL DEFAULT '',
    status        user_status  NOT NULL DEFAULT 'ENABLED',
    deleted       SMALLINT     NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_sys_user PRIMARY KEY (id),
    CONSTRAINT ck_sys_user_username CHECK (username = lower(username)),
    CONSTRAINT ck_sys_user_deleted CHECK (deleted IN (0, 1))
);

-- Unique among active rows only, so a deleted username can be reused.
CREATE UNIQUE INDEX IF NOT EXISTS uq_sys_user_username_active
    ON sys_user (username)
    WHERE deleted = 0;

-- ---------------------------------------------------------------------------
-- sys_role
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sys_role (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(32)  NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    description VARCHAR(255) NOT NULL DEFAULT '',
    status      role_status  NOT NULL DEFAULT 'ENABLED',
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted     SMALLINT     NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_sys_role PRIMARY KEY (id),
    CONSTRAINT ck_sys_role_code CHECK (code ~ '^[A-Z][A-Z0-9_]{0,31}$'),
    CONSTRAINT ck_sys_role_deleted CHECK (deleted IN (0, 1))
);

-- Unique among active rows only, so a deleted role code can be reused.
CREATE UNIQUE INDEX IF NOT EXISTS uq_sys_role_code_active
    ON sys_role (code)
    WHERE deleted = 0;

-- ---------------------------------------------------------------------------
-- sys_permission
-- ---------------------------------------------------------------------------
-- The catalog is code-owned and never deleted at runtime, hence no deleted column.
CREATE TABLE IF NOT EXISTS sys_permission (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    description VARCHAR(255) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_sys_permission PRIMARY KEY (id),
    CONSTRAINT uq_sys_permission_code UNIQUE (code),
    CONSTRAINT ck_sys_permission_code CHECK (code ~ '^[a-z][a-z0-9:_-]*$')
);

-- ---------------------------------------------------------------------------
-- sys_user_role
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id    BIGINT      NOT NULL,
    role_id    BIGINT      NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_sys_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_sys_user_role_user FOREIGN KEY (user_id)
        REFERENCES sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_user_role_role FOREIGN KEY (role_id)
        REFERENCES sys_role (id) ON DELETE CASCADE
);

-- The primary key covers user_id -> roles; this covers role_id -> users.
CREATE INDEX IF NOT EXISTS idx_sys_user_role_role_id ON sys_user_role (role_id);

-- ---------------------------------------------------------------------------
-- sys_role_permission
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sys_role_permission (
    role_id       BIGINT      NOT NULL,
    permission_id BIGINT      NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_sys_role_permission PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_sys_role_permission_role FOREIGN KEY (role_id)
        REFERENCES sys_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_sys_role_permission_permission FOREIGN KEY (permission_id)
        REFERENCES sys_permission (id) ON DELETE CASCADE
);

-- The primary key covers role_id -> permissions; this covers permission_id -> roles.
CREATE INDEX IF NOT EXISTS idx_sys_role_permission_permission_id
    ON sys_role_permission (permission_id);

